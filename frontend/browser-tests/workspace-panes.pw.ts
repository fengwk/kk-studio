import { test, expect, type Page, type Locator } from './fixture'

const url = '/browser-tests/workspace-panes-harness.html'
const active = (page: Page) => page.locator('[data-pane-active]')
const header = (pane: Locator) => pane.locator('[data-pane-header]')
const shot = (page: Page, name: string) => page.screenshot({ path: `../reports/r130-panes/${name}.png`, animations: 'disabled' })

async function stableHost(pane: Locator) {
  const host = await pane.elementHandle()
  await expect.poll(() => host.evaluate(el => el.querySelector('iframe')?.contentDocument?.title)).toBe('Persistent fixture')
  const refs = await host.evaluateHandle(el => ({
    parent: el.parentElement,
    content: el.querySelector('[data-pane-content]'),
    iframe: el.querySelector('iframe'),
    frameDocument: el.querySelector('iframe')?.contentDocument,
  }))
  return async () => {
    expect(await pane.evaluate((el, previous) => {
      const iframe = el.querySelector('iframe')
      return el === previous.host && el.parentElement === previous.refs.parent
        && el.querySelector('[data-pane-content]') === previous.refs.content && previous.refs.content?.parentElement === el
        && iframe === previous.refs.iframe && iframe?.contentDocument === previous.refs.frameDocument
    }, { host, refs })).toBe(true)
  }
}

test('preserves connected pane hosts through splitting, resizing, swapping, fullscreen, narrowing and closing', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(url)
  const pane = async () => page.locator(`[data-pane-id="${await active(page).getAttribute('data-pane-id')}"]`)
  const a = await pane(), stableA = await stableHost(a)
  await expect(a.getByRole('button', { name: 'Close pane' })).toHaveCount(0)
  await a.getByRole('button', { name: 'Split right' }).click()
  const b = await pane(), stableB = await stableHost(b)
  await expect(b.getByRole('button', { name: 'Split right' })).toHaveAttribute('aria-disabled', 'false')
  await header(b).press('s')
  const c = await pane(), stableC = await stableHost(c)
  await a.getByRole('button', { name: 'Split down' }).click()
  const d = await pane(), stableD = await stableHost(d)
  const allStable = async () => { await stableA(); await stableB(); await stableC(); await stableD() }
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(4)
  await expect(header(a)).toHaveCSS('height', '32px')
  await allStable()

  const separator = page.getByRole('separator').and(page.locator('[aria-orientation=vertical]'))
  await separator.press('ArrowRight')
  await expect(separator).toHaveAttribute('aria-valuenow', '55')
  const line = (await separator.boundingBox())!
  await page.mouse.move(line.x, line.y + 100)
  await page.mouse.down()
  await page.mouse.move(line.x - 144, line.y + 100, { steps: 4 })
  await page.mouse.up()
  await expect(separator).toHaveAttribute('aria-valuenow', '45')
  await separator.dblclick({ position: { x: 0.5, y: 100 } })
  await expect(separator).toHaveAttribute('aria-valuenow', '50')

  await a.locator('[data-pane-grip]').dragTo(header(c))
  await expect(c.locator('[data-pane-grip]')).toHaveText('A')
  await expect(a.locator('[data-pane-grip]')).toHaveText('D')
  await allStable()
  await shot(page, '1440')

  await b.locator('iframe').click()
  await expect(active(page)).toHaveAttribute('data-pane-id', (await b.getAttribute('data-pane-id'))!)
  await a.getByRole('button', { name: 'Fullscreen', exact: true }).click()
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(1)
  await expect(a).toBeVisible()
  await allStable()
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(4)
  await allStable()

  await page.setViewportSize({ width: 1024, height: 900 })
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(4)
  await expect(a.getByRole('button', { name: 'Split right' })).toHaveAttribute('aria-disabled', 'true')
  await shot(page, '1024')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(1)
  const switcher = page.getByRole('button', { name: 'Switch pane: D New view' })
  await switcher.click()
  const menu = page.getByRole('menu')
  await expect(menu.getByRole('menuitem')).toHaveText(['A: New view', 'B: New view', 'C: New view', 'D: New view', 'Close pane'])
  await shot(page, '390')
  await page.keyboard.press('Escape')
  await expect(switcher).toBeFocused()
  await switcher.click()
  await menu.getByRole('menuitem', { name: 'A: New view' }).click()
  await expect(c).toBeVisible()
  await allStable()

  await page.setViewportSize({ width: 320, height: 844 })
  const split = c.getByRole('button', { name: 'Split pane' })
  await expect(split).toHaveCSS('width', '44px')
  await expect(split).toHaveCSS('height', '44px')
  await split.click()
  await expect(menu.getByRole('menuitem')).toHaveText(['Split right', 'Split down'])
  await shot(page, '320')
  await page.keyboard.press('Escape')
  await c.getByRole('button', { name: 'Switch pane: A New view' }).click()
  await menu.getByRole('menuitem', { name: 'Close pane' }).click()
  await expect(c).toHaveCount(0)
  await expect(d).toBeVisible()
  await stableA(); await stableB(); await stableD()
  await d.getByRole('button', { name: 'Split pane' }).click()
  await menu.getByRole('menuitem', { name: 'Split right' }).click()
  await expect(page.locator('[data-pane-id]')).toHaveCount(4)
  await expect(page.locator('[data-pane-id]:visible')).toHaveCount(1)
  await active(page).getByRole('button', { name: 'Fullscreen', exact: true }).click()
  await active(page).getByRole('button', { name: 'Exit fullscreen' }).click()
  await expect(active(page).getByRole('button', { name: 'Split pane' })).toBeVisible()
  await stableA(); await stableB(); await stableD()
})

test('chooses a destination with keyboard or pointer, restores focus and persists by space', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(url)
  const alpha = page.getByRole('button', { name: 'Open Alpha' })
  const beta = page.getByRole('button', { name: 'Open Beta' })
  const picker = page.getByRole('dialog', { name: 'Open in pane' })
  await alpha.click()
  await expect(picker).toHaveCount(0)
  await expect(header(active(page))).toHaveText('Alpha')
  await active(page).getByRole('button', { name: 'Split right' }).click()
  await active(page).getByRole('textbox', { name: 'Draft' }).fill('draft')
  await beta.click()
  await expect(picker.getByRole('button', { name: 'B: New view' })).toBeFocused()
  await expect(picker.getByRole('button', { name: 'B: New view' })).toHaveAttribute('aria-current', 'true')
  await shot(page, '1440-picker')
  await page.keyboard.press('Escape')
  await expect(beta).toBeFocused()
  await expect(active(page).getByRole('textbox')).toHaveValue('draft')
  await beta.click()
  await page.keyboard.press('a')
  await expect(header(active(page))).toHaveText('ABeta')
  await expect(beta).toBeFocused()
  await page.setViewportSize({ width: 320, height: 844 })
  await alpha.click()
  await expect(picker.getByRole('button')).toHaveCount(2)
  await shot(page, '320-picker')
  await picker.getByRole('button', { name: 'B: New view' }).click()
  await expect(active(page).getByRole('button', { name: 'Switch pane: B Alpha' })).toBeVisible()
  await beta.click()
  await page.keyboard.press('Enter')
  await expect(active(page).getByRole('button', { name: 'Switch pane: B Beta' })).toBeVisible()
  await page.reload()
  await expect(active(page).getByRole('button', { name: 'Switch pane: B Beta' })).toBeVisible()
  const switchSpace = page.getByRole('button', { name: 'Switch space' })
  await switchSpace.click()
  await expect(page.locator('[data-pane-id]')).toHaveCount(1)
  await expect(header(active(page))).toHaveText('New view')
  await switchSpace.click()
  await expect(active(page).getByRole('button', { name: 'Switch pane: B Beta' })).toBeVisible()
})
